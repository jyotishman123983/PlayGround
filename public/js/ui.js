export function esc(value) {
  return String(value ?? '').replace(/[&<>"']/g, char => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[char]));
}

export function fmtNumber(value) {
  if (value === null || value === undefined) return '—';
  return new Intl.NumberFormat('en-IN').format(Number(value));
}

export function fmtDate(value, withTime = false) {
  if (!value) return '—';
  const date = new Date(value);
  if (Number.isNaN(date.getTime())) return '—';
  return date.toLocaleDateString('en-IN', {
    day: '2-digit', month: 'short', year: 'numeric',
    ...(withTime ? { hour: '2-digit', minute: '2-digit' } : {})
  });
}

export function timeAgo(value) {
  if (!value) return '—';
  const diff = Date.now() - new Date(value).getTime();
  if (diff < 60_000) return 'just now';
  if (diff < 3_600_000) return `${Math.floor(diff / 60_000)}m ago`;
  if (diff < 86_400_000) return `${Math.floor(diff / 3_600_000)}h ago`;
  if (diff < 604_800_000) return `${Math.floor(diff / 86_400_000)}d ago`;
  return fmtDate(value);
}

export function fmtDuration(seconds) {
  if (seconds === null || seconds === undefined) return '—';
  const total = Math.max(0, Math.round(Number(seconds)));
  const mins = Math.floor(total / 60);
  const secs = total % 60;
  if (mins >= 60) {
    const hours = Math.floor(mins / 60);
    return `${hours}h ${mins % 60}m`;
  }
  return mins > 0 ? `${mins}m ${secs}s` : `${secs}s`;
}

export function hashHue(value) {
  let hash = 0;
  for (let index = 0; index < String(value).length; index++) hash = ((hash << 5) - hash + String(value).charCodeAt(index)) | 0;
  return Math.abs(hash) % 360;
}

export const STATUS_LABELS = {
  queued: 'Queued',
  planning: 'Planning scenes',
  generating: 'Generating scenes',
  assembling: 'Assembling final video',
  completed: 'Completed',
  failed: 'Failed',
  cancelled: 'Cancelled'
};

export function statusBadge(status) {
  const tone = status === 'completed' ? 'live' : status === 'failed' ? 'red' : status === 'cancelled' ? 'amber' : 'violet';
  return `<span class="badge ${tone}">${esc(STATUS_LABELS[status] || status)}</span>`;
}

export function toast(message, type = 'info', timeout = 5200) {
  const host = document.getElementById('toasts');
  if (!host) return;
  const el = document.createElement('div');
  el.className = `toast ${type}`;
  const iconName = type === 'success' ? 'check' : type === 'error' ? 'alert' : type === 'warn' ? 'alert' : 'info';
  el.innerHTML = `${icon(iconName)}<div>${esc(message)}</div>`;
  host.appendChild(el);
  setTimeout(() => {
    el.classList.add('leaving');
    setTimeout(() => el.remove(), 220);
  }, timeout);
}
