import { useEffect, useRef, useState } from 'react'
import type { VideoRecord } from '../types'
import { Icon } from './Icon'
import { formatBytes, timeAgo } from '../lib/share'
import { styleMeta } from '../lib/presets'

interface VideoPreviewModalProps {
  record: VideoRecord
  src: string | null
  loading?: boolean
  onClose: () => void
  onDownload: () => void
  onShare: () => void
  onDelete: () => void
  shareLabel?: string
  hideDelete?: boolean
}

export function VideoPreviewModal({ record, src, loading = false, onClose, onDownload, onShare, onDelete, shareLabel = 'Share', hideDelete = false }: VideoPreviewModalProps) {
  const videoRef = useRef<HTMLVideoElement>(null)
  const [playing, setPlaying] = useState(false)
  const [failed, setFailed] = useState(false)

  useEffect(() => {
    const onKey = (event: KeyboardEvent) => {
      if (event.key === 'Escape') onClose()
    }
    window.addEventListener('keydown', onKey)
    document.body.classList.add('modal-open')
    return () => {
      window.removeEventListener('keydown', onKey)
      document.body.classList.remove('modal-open')
    }
  }, [onClose])

  useEffect(() => {
    setFailed(false)
  }, [src])

  const togglePlay = () => {
    const video = videoRef.current
    if (!video) return
    if (video.paused) {
      void video.play().then(() => setPlaying(true)).catch(() => setFailed(true))
    } else {
      video.pause()
      setPlaying(false)
    }
  }

  const isAi = record.isAiGenerated
  const style = styleMeta(record.style)

  return (
    <div className="modal-backdrop" role="dialog" aria-modal="true" aria-label="Video preview" onClick={onClose}>
      <div className="preview-modal" onClick={(event) => event.stopPropagation()}>
        <div className="preview-header">
          <div className="preview-heading">
            <span className={`source-badge ${isAi ? 'is-ai' : 'is-demo'}`}>
              <Icon name={isAi ? 'sparkles' : 'wand'} size={13} />
              {isAi ? 'AI generated' : 'Demo · not AI'}
            </span>
            <h2>{record.title}</h2>
            <p className="preview-sub">
              {style.label} · {record.aspect} · {record.duration}s · {timeAgo(record.createdAt)}
            </p>
          </div>
          <button type="button" className="icon-button" onClick={onClose} aria-label="Close preview">
            <Icon name="close" size={20} />
          </button>
        </div>

        <div className={`preview-stage ratio-${record.aspect.replace(':', '-')}`}>
          {loading && (
            <div className="preview-loading">
              <span className="spinner" />
              <span>Loading clip…</span>
            </div>
          )}
          {!loading && src && !failed && (
            <>
              <video
                ref={videoRef}
                src={src}
                poster={record.thumbnail}
                playsInline
                controls
                preload="metadata"
                onPlay={() => setPlaying(true)}
                onPause={() => setPlaying(false)}
                onError={() => setFailed(true)}
              />
              {!playing && (
                <button type="button" className="preview-play" onClick={togglePlay} aria-label="Play video">
                  <Icon name="play" size={34} filled />
                </button>
              )}
            </>
          )}
          {!loading && (!src || failed) && (
            <div className="preview-error">
              <Icon name="alert" size={30} />
              <p>This clip is not available.</p>
              <span>{record.remoteUrl ? 'The backend file could not be loaded.' : 'The locally stored file may have been cleared by the browser.'}</span>
            </div>
          )}
        </div>

        {!isAi && (
          <p className="preview-disclaimer">
            <Icon name="info" size={15} />
            This is a procedural clip rendered on your device by the ViralYantra demo engine. It was <strong>not</strong> generated by an AI model.
          </p>
        )}

        <div className="preview-actions">
          <button type="button" className="action-button" onClick={onDownload}>
            <Icon name="download" size={19} />
            Download
          </button>
          <button type="button" className="action-button" onClick={onShare}>
            <Icon name="share" size={19} />
            {shareLabel}
          </button>
          {!hideDelete && (
            <button type="button" className="action-button is-danger" onClick={onDelete}>
              <Icon name="trash" size={19} />
              Delete
            </button>
          )}
        </div>

        <dl className="preview-meta">
          <div>
            <dt>Engine</dt>
            <dd>{record.engineLabel}</dd>
          </div>
          <div>
            <dt>Resolution</dt>
            <dd>{record.width}×{record.height}</dd>
          </div>
          <div>
            <dt>File</dt>
            <dd>{record.mime.split(';')[0]} · {formatBytes(record.sizeBytes)}</dd>
          </div>
          <div>
            <dt>Prompt</dt>
            <dd className="preview-prompt">{record.prompt || '—'}</dd>
          </div>
        </dl>
      </div>
    </div>
  )
}
